#!/usr/bin/env python3
"""Reproduce the hashed Semgrep runtime lock from verified upstream sources.

Requires the uv version recorded in tools.lock.json, but performs no dependency
resolution. Use --source-dir with previously downloaded, matching pyproject.toml
and uv.lock for an entirely offline export. The image build consumes the checked
in requirements.lock and does not need uv or network access to GitHub sources.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import urllib.parse
import urllib.request
from pathlib import Path


def main() -> int:
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lock", type=Path, default=here / "tools.lock.json")
    parser.add_argument("--output", type=Path, default=here / "requirements.lock")
    parser.add_argument("--source-dir", type=Path)
    parser.add_argument("--uv", default="uv")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    locked = json.loads(args.lock.read_text())["python"]
    actual_uv = subprocess.check_output([args.uv, "--version"], text=True).split()[1]
    if actual_uv != locked["uv_version"]:
        raise ValueError(f"use uv {locked['uv_version']} to reproduce this lock; found {actual_uv}")
    with tempfile.TemporaryDirectory(prefix="boxoro-semgrep-lock-") as temporary:
        project = Path(temporary)
        for source in locked["upstream_files"]:
            if source["name"] not in ("pyproject.toml", "uv.lock"):
                raise ValueError("unexpected upstream lock file")
            if args.source_dir:
                content = (args.source_dir / source["name"]).read_bytes()
            else:
                url = urllib.parse.urlsplit(source["url"])
                if url.scheme != "https" or url.hostname != "raw.githubusercontent.com":
                    raise ValueError("upstream source must use raw.githubusercontent.com over HTTPS")
                with urllib.request.urlopen(source["url"], timeout=60) as response:
                    if response.geturl() != source["url"]:
                        raise ValueError("unexpected redirect for upstream lock")
                    content = response.read(2 * 1024 * 1024)
            if hashlib.sha256(content).hexdigest() != source["sha256"]:
                raise ValueError("upstream SHA-256 mismatch: " + source["name"])
            (project / source["name"]).write_bytes(content)
        # Explicit flags and a clean uv environment prevent local configuration
        # from changing groups, hashes, indexes or Python downloads.
        environment = {k: v for k, v in os.environ.items() if not k.startswith("UV_")}
        result = subprocess.run([
            args.uv, "export", "--offline", "--frozen", "--no-dev", "--no-emit-project",
            "--no-header", "--no-annotate", "--format", "requirements-txt",
            "--no-python-downloads", "--no-config",
        ], cwd=project, env=environment, capture_output=True, text=True, check=True)
        requirements = result.stdout.strip()
    if not requirements or "--hash=sha256:" not in requirements:
        raise ValueError("uv did not export hashed runtime dependencies")
    for line in requirements.splitlines():
        if line and not line.startswith((" ", "#")) and not re.match(r"[A-Za-z0-9_.-]+==", line):
            raise ValueError("unexpected dependency directive in frozen export")
    hashes = locked["wheel_hashes"]
    if not hashes or any(not re.fullmatch(r"[0-9a-f]{64}", h) for h in hashes):
        raise ValueError("invalid Semgrep wheel hash")
    output = (
        "# Generated by deploy/security/lock-python.py; do not hand edit.\n"
        "# Frozen upstream runtime dependencies, plus the verified Linux amd64 Semgrep wheel.\n"
        "# Install with --require-hashes --only-binary=:all: on Ubuntu 24.04 / CPython 3.12.\n"
        + requirements + "\nsemgrep==" + locked["semgrep_version"] + " \\\n"
        + " \\\n".join("    --hash=sha256:" + digest for digest in hashes) + "\n"
    )
    if args.check:
        if not args.output.exists() or args.output.read_text() != output:
            raise ValueError("requirements.lock differs from the verified frozen export")
        print("requirements.lock matches the verified upstream runtime lock")
    else:
        args.output.write_text(output)
        print(f"wrote {args.output} ({len(output.encode())} bytes)")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, KeyError, subprocess.SubprocessError) as error:
        print("Python lock generation failed: " + str(error), file=sys.stderr)
        sys.exit(1)
